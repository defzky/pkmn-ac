/* fetch-evo.mjs — PokeAPI evolution chains → src/data/evo-map.ts
 * Run: node tools/fetch-evo.mjs  (network only at generation; output committed)
 * Map: base dex → [stage2, stage3]. Branched chains (Eevee) take first path.
 * Chains filtered to dex present in src/data/pokedex.js.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const POKEAPI = 'https://pokeapi.co/api/v2';

function pokedexDexes() {
  const src = readFileSync(new URL('../src/data/pokedex.js', import.meta.url), 'utf8');
  const out = new Set();
  for (const m of src.matchAll(/"dex":(\d+)/g)) out.add(+m[1]);
  return out;
}

/** Flatten chain [{species{name,url}, evolves_to[]}] → ordered species stages. */
function flatten(chain, path = []) {
  const cur = [...path, chain.species];
  if (!chain.evolves_to.length) return [cur];
  // branched (Eevee): follow first branch only
  return flatten(chain.evolves_to[0], cur);
}

async function get(url) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${url} → ${r.status}`);
  return r.json();
}

const dexes = pokedexDexes();
const list = await get(`${POKEAPI}/evolution-chain?limit=1000`);
console.log(`chains: ${list.count}`);

const map = {};
const urls = list.results.map((r) => r.url);
let done = 0;
const CONC = 12;
for (let i = 0; i < urls.length; i += CONC) {
  await Promise.all(urls.slice(i, i + CONC).map(async (u) => {
    const c = await get(u);
    done++;
    if (done % 100 === 0) console.log(`  ${done}/${urls.length}`);
    const paths = [];
    const walk = (node, path) => {
      const p = [...path, node.species];
      if (!node.evolves_to.length) { paths.push(p); return; }
      for (const n of node.evolves_to) walk(n, p);
    };
    walk(c.chain, []);
    // pick path whose base is in our dex, longest useful prefix
    const path = paths.find((p) => dexes.has(speciesId(p[0]))) || paths[0];
    const ids = path.map(speciesId);
    const base = ids[0];
    if (!dexes.has(base) || ids.length < 2) return;
    const s2 = ids[1] ?? 0;
    const s3 = ids[2] ?? 0;
    // only stages that exist in our pokedex (else 0 → no evol at that star)
    map[base] = [dexes.has(s2) ? s2 : 0, dexes.has(s3) ? s3 : 0];
  }));
}

function speciesId(sp) {
  const m = sp.url.match(/(\d+)\/$/);
  return m ? +m[1] : 0;
}

const keys = Object.keys(map).length;
const header = `/* evo-map.ts — GENERATED by tools/fetch-evo.mjs (PokeAPI evolution-chain). Do not edit by hand.
 * base dex → [stage2, stage3]; 0 = no evolution at that stage (or stage absent in pokedex).
 */
export const EVO: Record<number, [number, number]> = {
`;
const lines = Object.entries(map)
  .map(([b, [s2, s3]]) => `  ${b}: [${s2}, ${s3}],`)
  .join('\n');
writeFileSync(new URL('../src/data/evo-map.ts', import.meta.url), `${header}${lines}\n};\n`);
console.log(`wrote evo-map.ts: ${keys} entries`);
